def modbus_polynomial(data):
    register=0xffff
    for byte in data:
        reflected=int(format(byte,'08b')[::-1],2)
        numerator=(register^(reflected<<8))<<8
        for degree in range(23,15,-1):
            if numerator&(1<<degree):numerator^=0x18005<<(degree-16)
        register=numerator
    return int(format(register,'016b')[::-1],2)
