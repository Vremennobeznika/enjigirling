const {test,expect}=require('@playwright/test');
test('education search, college filter, reset and more results work',async({page})=>{
 const errors=[];
 page.on('pageerror',err=>errors.push(err.message));
 await page.goto('/map.html');
 await expect(page.locator('main h1')).toHaveText('Где учиться инженерному делу');
 await expect(page.locator('#educationDistrict option')).toHaveCount(9);
 await expect(page.locator('#educationResults .education-card')).toHaveCount(12);
 await expect(page.locator('#educationStatus')).toContainText('из ');
 await page.locator('#educationSearch').fill('СПбПУ');
 await expect(page.locator('#educationResults .education-card')).toHaveCount(1);
 await expect(page.locator('#educationResults')).toContainText('Санкт-Петербург');
 await page.locator('#educationType').selectOption('college');
 await expect(page.locator('.education-empty')).toBeVisible();
 await page.locator('#educationClear').click();
 await expect(page.locator('#educationSearch')).toHaveValue('');
 await expect(page.locator('#educationResults .education-card')).toHaveCount(12);
 await expect(page.locator('#education-map')).not.toHaveAttribute('open','');
 await page.locator('a[href="#education-map"]').click();
 await expect(page.locator('#education-map')).toHaveAttribute('open','');
 await page.locator('#educationDistrict').selectOption('northwest');
 await expect(page.locator('.eng-district[data-id="northwest"]')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#districtInfo')).toContainText('Северо-Западный');
 await page.locator('#educationDistrict').selectOption('');
 await page.locator('#educationMore').click();
 await expect(page.locator('#educationResults .education-card')).toHaveCount(24);
 await page.locator('#educationSearch').fill('____no_match____');
 await expect(page.locator('.education-empty')).toBeVisible();
 await expect(page.locator('#educationMore')).toBeHidden();
 expect(errors).toEqual([]);
});
test('school details remain compact, official sites accessible and map keyboard selectable',async({page})=>{
 await page.goto('/map.html');
 await page.locator('#educationType').selectOption('uni');
 const first=page.locator('#educationResults .education-card').first();
 await expect(first.locator('dl')).not.toBeVisible();
 await first.locator('summary').click();
 await expect(first.locator('dl')).toBeVisible();
 const sourceLinks=first.locator('a.education-site');
 expect(await sourceLinks.count()).toBeGreaterThan(0);
 for(const link of await sourceLinks.all())await expect(link).toHaveAttribute('rel','noopener noreferrer');
 await page.locator('#educationDistrict').selectOption('');
 await page.locator('#educationMore').click();
 await expect(first.locator('details')).toHaveAttribute('open','');
 await page.locator('#education-map > summary').click();
 const district=page.locator('.eng-district[data-id="central"]');
 await district.focus();
 await page.keyboard.press('Enter');
 await expect(page.locator('#educationDistrict')).toHaveValue('central');
 await expect(district).toHaveAttribute('aria-pressed','true');
 await page.locator('#mapReset').click();
 await expect(page.locator('#educationDistrict')).toHaveValue('');
 await page.locator('a[href="#education-calculators"]').click();
 await expect(page.locator('#education-calculators')).toHaveAttribute('open','');
 await expect(page.locator('#salaryProfession option')).toHaveCount(54);
 await page.locator('a[href="#education-benefits"]').click();
 await expect(page.locator('#education-benefits .benefit-card')).toHaveCount(16);
 await page.locator('a[href="#education-courses"]').click();
 await expect(page.locator('#education-courses .benefit-card')).toHaveCount(10);
});
test('map redesigned for 320px: filters accessible and no horizontal overflow',async({page})=>{
 await page.setViewportSize({width:320,height:720});
 await page.goto('/map.html');
 await expect(page.locator('#educationSearch')).toBeVisible();
 await page.locator('#educationSearch').fill('Энергетика');
 await expect(page.locator('.education-card').first()).toBeVisible();
 await page.locator('a[href="#education-map"]').click();
 await expect(page.locator('#russiaMap')).toBeVisible();
 const dims=await page.evaluate(()=>({content:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
 expect(dims.content).toBeLessThanOrEqual(dims.viewport+2);
 await expect(page.locator('nav.eng-tabs a')).toHaveCount(12);
});
